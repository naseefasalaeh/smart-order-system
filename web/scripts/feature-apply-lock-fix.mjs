// Guarded follow-up migration; no hosted concurrency test or business DML.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {native,privateRoot} from './feature-postgres-local.mjs';
import {remoteConnection} from './feature-remote-connection.mjs';
const backup=path.join(privateRoot,'before-lock-fix');
const read=file=>JSON.parse(fs.readFileSync(file,'utf8'));
const name='20261101000000_member_recovery_lock_order';
const source=fs.readFileSync(`supabase/migrations/${name}.sql`,'utf8');
const sha=createHash('sha256').update(source).digest('hex');
const proof=read(path.join(privateRoot,'member-lock-order-verification.json'));
assert.ok(proof.oldLockCycleReproduced&&proof.fixedConcurrentOrderAndRecovery&&proof.rollbackDefinitionAndHistory&&proof.functionPermissionsUnchanged);
assert.equal(sha,proof.migrationSha256);
const concurrency=read(path.join(privateRoot,'postgres-concurrency.json'));
assert.ok(concurrency.allPassed&&concurrency.lockWaitObserved);assert.equal(sha,concurrency.testedMigrationSha256[name]);
assert.ok(read(path.join(backup,'restore-verification.json')).dataAndSequencesMatch);
for(const [file,entry] of Object.entries(read(path.join(backup,'manifest.json')).files))assert.equal(createHash('sha256').update(fs.readFileSync(path.join(backup,file))).digest('hex'),entry.sha256);
const env=await remoteConnection();
const current=JSON.parse((await native('psql',['-X','-qAt','-v','ON_ERROR_STOP=1','-c','set role postgres','-f','supabase/feature-data-fingerprint.sql'],{env})).stdout);
assert.deepEqual(current,read(path.join(backup,'remote-fingerprint-before.private.json')),'Data changed after the fresh backup; stop and re-backup');
const history=JSON.parse((await native('psql',['-X','-qAt','-c','set role postgres;select jsonb_agg(version order by version) from supabase_migrations.schema_migrations'],{env})).stdout);
const expected=fs.readdirSync('supabase/migrations').filter(file=>file.endsWith('.sql')&&!file.startsWith('20261101000000')).map(file=>file.slice(0,14)).sort();
assert.deepEqual(history,expected);
const quote=value=>`'${value.replaceAll("'","''")}'`;
const body=source.replace(/^begin;\s*/i,'').replace(/commit;\s*$/i,'');
const statement=`set role postgres;begin;${body}\ninsert into supabase_migrations.schema_migrations(version,name,statements) values('20261101000000','member_recovery_lock_order',array[${quote(source)}]::text[]);notify pgrst,'reload schema';commit;`;
const file=path.join(backup,'apply-lock-fix.private.sql');fs.writeFileSync(file,statement);
await native('psql',['-X','-q','-v','ON_ERROR_STOP=1','-f',file],{env});
const result={at:new Date().toISOString(),migration:name,sha256:sha,appliedAtomicallyWithHistory:true,freshBackupAndRestoreVerified:true,nativeLockCycleAndFixVerified:true};
fs.writeFileSync(path.join(privateRoot,'lock-fix-applied.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
