import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { test } from 'node:test';

test('partial cooking/service, migration history, FCFS, retries, audit, payment and roles', async () => {
  const db = new PGlite();
  const migration = n => readFileSync(`supabase/migrations/${n}.sql`, 'utf8');
  const query = async (sql, params = []) => (await db.query(sql, params)).rows;
  const admin = '00000000-0000-4000-8000-000000000091';
  const staff = '00000000-0000-4000-8000-000000000092';
  const kitchen = '00000000-0000-4000-8000-000000000093';
  const as = async (id = '') => {
    await db.exec('reset role');
    await query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
    if (id) await db.exec('set role authenticated');
  };
  try {
    const setup = readFileSync('tests/active-accounts.test.mjs','utf8');
    await new Function('db','migration','readFileSync',`return (async () => {${setup.slice(setup.indexOf('  await db.exec(readFileSync'),setup.indexOf('  const as='))}})()`)(db,migration,readFileSync);
    for (const n of ['20260923100000_served_order_payment','20261005000000_isolate_operational_roles','20261025000000_kitchen_fcfs_plates']) await db.exec(migration(n));
    await query("insert into profiles(id,role,is_active) values($1,'kitchen_staff',true)",[kitchen]);
    const create = async (status = 'confirmed', quantity = 1) => {
      const [{id}] = await query("insert into orders(table_id,status,total_amount,stock_deducted,dining_type) values(1,$1,150,true,'dine_in') returning id",[status]);
      const [item] = await query('insert into order_items(order_id,menu_id,quantity,unit_price,subtotal) select $1,id,$2,50,50*$2 from menus order by id limit 1 returning id',[id,quantity]);
      return {id,item:item.id};
    };
    const historical = await create('served',2), legacyReady = await create('ready',3), oldCooked = await create('preparing',1);
    await query("update order_items set completed_plates='{1}' where id=$1",[oldCooked.item]);
    const before = await query('select id,status,total_amount,served_at,served_by from orders order by id');
    await db.exec(migration('20261025010000_partial_plate_service'));
    const after = await query('select id,status,total_amount,served_at,served_by from orders order by id');
    assert.deepEqual(after.filter(order => order.id !== oldCooked.id),before.filter(order => order.id !== oldCooked.id));
    assert.equal(after.find(order => order.id === oldCooked.id).status,'ready','old fully cooked orders release the kitchen queue');
    assert.deepEqual((await query('select completed_plates,served_plates from order_items where id=$1',[historical.item]))[0],{completed_plates:[1,2],served_plates:[1,2]});
    assert.deepEqual((await query('select completed_plates,served_plates from order_items where id=$1',[legacyReady.item]))[0],{completed_plates:[1,2,3],served_plates:[]});
    await query("update orders set status='cancelled' where status in ('confirmed','preparing')");
    const first = await create('confirmed',2), second = await create('confirmed',1);
    const [extra] = await query('insert into order_items(order_id,menu_id,quantity,unit_price,subtotal) select $1,id,1,50,50 from menus order by id limit 1 returning id',[first.id]);
    const stocks = await query('select id,stock_quantity from ingredients order by id');
    await as(kitchen);
    await assert.rejects(query("select advance_order_status($1,'confirmed','preparing')",[second.id]),/WAIT_PREVIOUS_ORDER/);
    await query("select advance_order_status($1,'confirmed','preparing')",[first.id]);
    await query('select set_kitchen_plate($1,1,true)',[first.item]);
    await as(staff);
    await assert.rejects(query('select serve_order_plate($1,2)',[first.item]),/PLATE_NOT_READY/);
    await assert.rejects(query('select serve_order_plate($1,0)',[first.item]),/INVALID_PLATE/);
    await assert.rejects(query('select serve_order($1)',[first.id]),/ORDER_NOT_READY/);
    await Promise.all([query('select serve_order_plate($1,1)',[first.item]),query('select serve_order_plate($1,1)',[first.item])]);
    const [audit] = await query('select * from order_plate_services where order_item_id=$1',[first.item]);
    assert.equal(audit.served_by,staff);
    assert.equal((await query('select * from order_plate_services where order_item_id=$1',[first.item])).length,1);
    assert.equal((await query('select status from orders where id=$1',[first.id]))[0].status,'preparing');
    await assert.rejects(query("select complete_order_payment($1,'cash')",[first.id]),/ORDER_NOT_SERVED/);
    await as(kitchen);
    await assert.rejects(query('select set_kitchen_plate($1,1,false)',[first.item]),/PLATE_ALREADY_SERVED/);
    await assert.rejects(query("select advance_order_status($1,'confirmed','preparing')",[second.id]),/WAIT_PREVIOUS_ORDER/);
    await query('select set_kitchen_plate($1,2,true)',[first.item]);
    await query('select set_kitchen_plate($1,1,true)',[extra.id]);
    assert.equal((await query('select status from orders where id=$1',[first.id]))[0].status,'ready');
    await query('select set_kitchen_plate($1,1,true)',[extra.id]);
    await query("select advance_order_status($1,'confirmed','preparing')",[second.id]);
    await assert.rejects(query('select serve_order_plate($1,2)',[first.item]),/STAFF_ROLE_REQUIRED/);
    await as(staff);
    await assert.rejects(query('select set_kitchen_plate($1,1,true)',[second.item]),/KITCHEN_ROLE_REQUIRED/);
    await Promise.all([query('select serve_order_plate($1,2)',[first.item]),query('select serve_order_plate($1,1)',[extra.id])]);
    const [served] = await query('select status,served_at,served_by from orders where id=$1',[first.id]);
    assert.equal(served.status,'served'); assert.equal(served.served_by,staff); assert.ok(served.served_at);
    await query('select serve_order_plate($1,1)',[first.item]);
    assert.deepEqual((await query('select * from order_plate_services where order_item_id=$1 and plate=1',[first.item]))[0],audit);
    await query("select complete_order_payment($1,'cash')",[first.id]);
    await assert.rejects(query("select complete_order_payment($1,'qr_code')",[first.id]),/ORDER_NOT_SERVED/);
    assert.equal(Number((await query('select amount from payments where order_id=$1',[first.id]))[0].amount),150);
    await query('select serve_order_plate($1,1)',[first.item]);
    await query('select serve_order($1)',[legacyReady.id]);
    assert.equal((await query('select status from orders where id=$1',[legacyReady.id]))[0].status,'served');
    await assert.rejects(query("update order_items set served_plates='{1}' where id=$1",[second.item]),/permission denied/);
    await assert.rejects(query('delete from order_plate_services where order_item_id=$1',[first.item]),/permission denied/);
    await as(admin);
    await assert.rejects(query('select serve_order_plate($1,1)',[second.item]),/STAFF_ROLE_REQUIRED/);
    await as();
    assert.deepEqual(await query('select id,stock_quantity from ingredients order by id'),stocks);
    await query('update profiles set is_active=false where id=$1',[staff]);
    await as(staff);
    await assert.rejects(query('select serve_order_plate($1,1)',[second.item]),/STAFF_ROLE_REQUIRED/);
    await as(); await db.exec('set role anon');
    await assert.rejects(query('select serve_order_plate($1,1)',[second.item]),/permission denied/);
  } finally { await db.close(); }
});
