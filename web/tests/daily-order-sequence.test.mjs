import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { test } from 'node:test';

test('daily order sequence reset migration schedules daily reset and resets to 1', async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role;
      create table public.orders(
        id uuid default gen_random_uuid() not null,
        order_number bigint generated by default as identity not null,
        created_at timestamptz default now() not null
      );
      alter table public.orders add constraint orders_order_number_key unique (order_number);
      create schema if not exists cron;
      create table if not exists cron.job(jobname text primary key,schedule text,command text,active boolean default true);
      create or replace function cron.schedule(text,text,text) returns bigint language sql as $$
        insert into cron.job(jobname,schedule,command) values($1,$2,$3)
        on conflict(jobname) do update set schedule=excluded.schedule,command=excluded.command returning 1::bigint $$;
      create or replace function cron.unschedule(text) returns boolean language sql as $$
        delete from cron.job where jobname=$1; select true; $$;
    `);

    const migration = readFileSync('supabase/migrations/20261107000000_daily_order_sequence_reset.sql', 'utf8')
      .replace('create extension if not exists pg_cron with schema pg_catalog;', '');
    const rollback = readFileSync('supabase/rollback/20261107000000_daily_order_sequence_reset.sql', 'utf8');

    // Test apply migration
    await db.exec(migration);

    // Verify cron job is registered
    const jobs = (await db.query("select jobname, schedule, command from cron.job where jobname = 'smart-order-daily-order-reset';")).rows;
    assert.equal(jobs.length, 1);
    assert.equal(jobs[0].schedule, '0 17 * * *');

    // Day 1: Insert 2 orders
    await db.exec("insert into public.orders default values;");
    await db.exec("insert into public.orders default values;");
    let rows = (await db.query('select order_number from public.orders order by order_number;')).rows;
    assert.deepEqual(rows.map(r => r.order_number), [1, 2]);

    // Midnight arrives: cron job triggers reset_daily_order_sequence()
    await db.exec("select public.reset_daily_order_sequence();");

    // Day 2: Insert 2 orders -> should restart from 1, 2
    await db.exec("insert into public.orders default values;");
    await db.exec("insert into public.orders default values;");
    rows = (await db.query('select order_number from public.orders;')).rows;
    assert.deepEqual(rows.map(r => r.order_number), [1, 2, 1, 2]);

    // Test rollback
    await db.exec(rollback);
    const remainingJobs = (await db.query("select * from cron.job where jobname = 'smart-order-daily-order-reset';")).rows;
    assert.equal(remainingJobs.length, 0);

    // Re-apply migration to ensure idempotency
    await db.exec(migration);
  } finally {
    await db.close();
  }
});
