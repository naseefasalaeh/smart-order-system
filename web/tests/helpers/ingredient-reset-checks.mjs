import assert from 'node:assert/strict';

export async function checkIngredientResets({page,mock,dir}) {
  mock.state.role='admin';
  const before=mock.state.rpcCalls.length;
  await page.goto('http://localhost:4400/dashboard/ingredients/1/edit');
  const mode=page.getByLabel('รอบรีเซ็ต',{exact:true});
  assert.equal(await mode.inputValue(),'none');
  assert.equal(await page.locator('[name=reset_start_date]').count(),0);
  await mode.selectOption('daily');
  await page.getByLabel('วันเริ่มต้น',{exact:true}).fill('2030-01-01');
  await page.getByLabel('เวลารีเซ็ต (เวลาไทย)',{exact:true}).fill('23:59');
  await page.locator('[name=stock_quantity]').fill('500');
  await page.getByRole('button',{name:'บันทึกการแก้ไข',exact:true}).click();
  await page.waitForURL('**/dashboard/ingredients');
  assert.match(await page.locator('tbody').innerText(),/รีเซ็ตทุกวัน เวลา 23:59/);
  const saved=mock.state.rpcCalls.slice(before).find(call=>call.path.endsWith('/save_ingredient'));
  assert.equal(saved.body.p_values.reset_every_days,1);
  assert.equal(saved.body.p_values.stock_quantity,500);
  assert.equal(saved.body.p_values.reset_start_date,'2030-01-01');
  assert.ok(saved.body.p_expected_updated_at);
  await page.goto('http://localhost:4400/dashboard/ingredients/1/edit');
  assert.equal(await mode.inputValue(),'daily');
  assert.equal(await page.getByLabel('เวลารีเซ็ต (เวลาไทย)',{exact:true}).inputValue(),'23:59');
  await mode.selectOption('interval');
  await page.getByLabel('ทุกกี่วัน',{exact:true}).fill('3');
  await page.setViewportSize({width:375,height:950});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:`${dir}/ingredient-reset-mobile.png`,fullPage:true});
  await page.getByRole('button',{name:'บันทึกการแก้ไข',exact:true}).click();
  await page.waitForURL('**/dashboard/ingredients');
  assert.equal(mock.state.catalog.ingredients[0].reset_every_days,3);
  assert.equal(Object.hasOwn(mock.state.rpcCalls.at(-1).body.p_values,'stock_quantity'),false,'unchanged field does not overwrite a reset or deduction');
  await page.goto('http://localhost:4400/dashboard/ingredients/1/edit');
  await mode.selectOption('none');
  await page.getByRole('button',{name:'บันทึกการแก้ไข',exact:true}).click();
  await page.waitForURL('**/dashboard/ingredients');
  assert.equal(mock.state.catalog.ingredients[0].reset_every_days,null);
  assert.equal(mock.state.catalog.ingredients[0].stock_quantity,500);
  await page.goto('http://localhost:4400/dashboard/ingredients/new');
  assert.equal(await mode.inputValue(),'none');
  await page.getByLabel('ชื่อวัตถุดิบ',{exact:true}).fill('TEST seasoning carry forward');
  await page.locator('[name=unit]').selectOption('กรัม');
  await page.locator('[name=stock_quantity]').fill('99');
  await page.locator('[name=minimum_stock]').fill('1');
  await page.getByRole('button',{name:'บันทึกวัตถุดิบ',exact:true}).click();
  await page.waitForURL('**/dashboard/ingredients');
  const seasoning=mock.state.catalog.ingredients.find(item=>item.name==='TEST seasoning carry forward');
  assert.equal(seasoning.reset_every_days,null);
  assert.equal(seasoning.stock_quantity,99);
  // A second terminal/cron updates the row while the form is open.
  await page.goto('http://localhost:4400/dashboard/ingredients/1/edit');
  mock.state.catalog.ingredients[0].updated_at='2030-01-01T00:00:00.000Z';
  await page.locator('[name=stock_quantity]').fill('200');
  await page.getByRole('button',{name:'บันทึกการแก้ไข',exact:true}).click();
  await page.getByText('ข้อมูลสต็อกเปลี่ยนแล้ว กรุณาตรวจยอดล่าสุดและบันทึกอีกครั้ง',{exact:true}).waitFor();
  assert.equal(mock.state.catalog.ingredients[0].stock_quantity,500);
  mock.state.role='staff';
  assert.equal((await page.goto('http://localhost:4400/dashboard/ingredients/1/edit')).status(),403);
  delete mock.state.catalog.ingredients;
  console.log('PASS: default no reset, daily/interval persistence, Thai time, mobile, disabled schedule, metadata-only saves, stale form and role protection');
}
